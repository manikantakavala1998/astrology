const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const origin = process.env.ASTRO_TEST_URL || 'http://127.0.0.1:8765';
const output = path.resolve('test-results');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1536, height: 1000}, timezoneId: 'America/Los_Angeles'});
  page.setDefaultTimeout(30000);
  await page.addInitScript(() => {Date.now = () => Date.UTC(2026, 9, 11, 8, 0);});
  const errors = [], external = [];
  let failNext = false;
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', route => {
    if (new URL(route.request().url()).origin !== origin) {external.push(route.request().url()); return route.abort();}
    if (failNext && route.request().url().includes('/api/vimshottari/subperiods')) {failNext = false; return route.fulfill({status: 500, body: 'Simulated branch error'});}
    return route.continue();
  });
  const nav = page.getByRole('navigation', {name: 'Astrology sections'});
  const panel = id => page.locator(`#panel-${id}`);
  const ready = id => panel(id).locator('.bhrigu-dasha-path[aria-busy="false"]').waitFor();
  const planets = id => panel(id).locator('.bhrigu-dasha-step strong').allTextContents();
  const setMoment = async (id, value) => {await panel(id).getByLabel('Date within year', {exact: true}).fill(value.slice(0, 10).split('-').reverse().join('/')); await panel(id).getByLabel('Time within year', {exact: true}).fill(value.slice(11));};
  const overflow = async () => assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No page overflow');
  const shot = async name => {await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({path: path.join(output, name), fullPage: true});};
  try {
    await page.goto(origin);
    await page.locator('#name').fill('Manikanta Kavala');
    await page.locator('#birth_date').fill('04/09/1998');
    await page.locator('#birth_hour').selectOption('12');
    await page.locator('#birth_minute').selectOption('3');
    await page.getByText('Advanced settings', {exact: true}).click();
    await page.locator('#manual_latitude').fill('17.00517');
    await page.locator('#manual_longitude').fill('81.77784');
    await page.locator('#manual_utc_offset_hours').fill('5.5');
    await page.getByRole('button', {name: 'Generate chart', exact: true}).click();
    await page.locator('#panel-chart .rasi-grid').waitFor();
    await nav.getByRole('button', {name: 'Bhrigu Chakra Paddhati', exact: true}).click();
    await ready('bcp');
    assert.equal(await panel('bcp').getByLabel('Running year', {exact: true}).inputValue(), '29');
    assert.deepEqual(await planets('bcp'), ['Rahu', 'Venus', 'Sun', 'Mercury', 'Venus']);
    assert.equal(await panel('bcp').getByRole('table', {name: 'Active dasha times', exact: true}).locator('tbody tr[aria-current="true"]').count(), 5);
    assert.ok((await panel('bcp').getByRole('table', {name: 'BCP progression comparison', exact: true}).innerText()).includes('D1 H8'));
    const aspects = await panel('bcp').getByRole('table', {name: 'Bhrigu aspects', exact: true}).innerText();
    for (const expected of ['Jupiter', 'Pisces', 'Virgo', 'None', 'Mercury', 'Venus']) assert.ok(aspects.includes(expected));
    assert.equal(await panel('bcp').locator('.bhrigu-year-summary > div').count(), 3);
    assert.equal(await panel('bcp').locator('.bhrigu-natal-cell strong .planet-color-jupiter').count(), 1);
    const prediction = id => panel(id).locator('.bhrigu-predictions');
    assert.equal(await prediction('bcp').getAttribute('data-year'), '29');
    assert.ok((await prediction('bcp').innerText()).includes('learning, creativity and children'));
    const cycleCard = prediction('bcp').locator('.bhrigu-prediction-cards article').filter({hasText: 'Cycle ruler adds a second focus'});
    assert.ok((await cycleCard.innerText()).includes('H5 from Venus brings learning, creativity and children'));
    assert.ok((await cycleCard.innerText()).includes('D1 H8'));
    assert.ok(!(await cycleCard.innerText()).includes('shared resources, research and changes'), 'Cycle focus uses the fifth from Venus, rather than D1 eighth-house themes');
    await prediction('bcp').getByText('Detailed year predictions & calculations', {exact: true}).click();
    const cycleLord = prediction('bcp').getByRole('table', {name: 'Year prediction calculations', exact: true}).locator('tbody tr').filter({hasText: 'Cycle-house lord connection'});
    assert.ok((await cycleLord.innerText()).includes('Jupiter rules H5, H8 from Venus'));
    assert.ok((await cycleLord.innerText()).includes('Pisces, H8 from Venus'));
    assert.ok((await cycleLord.innerText()).includes('D1 H11'));
    await prediction('bcp').getByText('Detailed year predictions & calculations', {exact: true}).click();
    assert.ok((await prediction('bcp').locator('.bhrigu-prana-reading').innerText()).includes('Prana: Venus'));
    await prediction('bcp').getByText('All five dasha readings & calculations', {exact: true}).click();
    assert.equal(await prediction('bcp').getByRole('table', {name: 'Dasha prediction calculations', exact: true}).locator('tbody tr').count(), 5);
    assert.ok((await prediction('bcp').getByRole('table', {name: 'Dasha prediction calculations', exact: true}).innerText()).includes('rules target H5'));
    await prediction('bcp').getByText('All five dasha readings & calculations', {exact: true}).click();
    await overflow();
    await prediction('bcp').screenshot({path: path.join(output, 'bhrigu-bcp-predictions.png')});
    await shot('bhrigu-bcp-desktop.png');
    // A Prana boundary changes only the fifth level.
    await setMoment('bcp', '2026-10-12T20:23:15');
    await ready('bcp');
    assert.deepEqual(await planets('bcp'), ['Rahu', 'Venus', 'Sun', 'Mercury', 'Sun']);
    assert.ok((await prediction('bcp').locator('.bhrigu-prana-reading').innerText()).includes('Prana: Sun'));
    await panel('bcp').getByRole('button', {name: 'Open full dasha explorer', exact: false}).click();
    await page.locator('.vimshottari-level[data-level="4"] .vimshottari-period[aria-pressed="true"]').waitFor();
    assert.equal(await page.locator('#vimshottari-date').inputValue(), '2026-10-12T20:23:15');
    await nav.getByRole('button', {name: 'Bhrigu Chakra Paddhati', exact: true}).click();
    await panel('bcp').getByRole('button', {name: 'Today', exact: true}).click();
    await ready('bcp');
    assert.deepEqual(await planets('bcp'), ['Rahu', 'Venus', 'Sun', 'Mercury', 'Venus']);
    // Error recovery is explicit, without leaving stale short-period rows.
    failNext = true;
    await panel('bcp').getByLabel('Running year', {exact: true}).selectOption('1');
    await panel('bcp').getByRole('alert').waitFor();
    assert.ok((await panel('bcp').getByRole('alert').innerText()).includes('could not be calculated'));
    await panel('bcp').getByRole('button', {name: 'Retry', exact: true}).click();
    await ready('bcp');
    assert.equal((await planets('bcp'))[0], 'Moon');
    assert.equal(await panel('bcp').getByLabel('Date within year', {exact: true}).inputValue(), '04/09/1998');
    assert.equal(await panel('bcp').getByLabel('Time within year', {exact: true}).inputValue(), '00:03:00');
    assert.equal(await prediction('bcp').getAttribute('data-year'), '1');
    assert.ok((await prediction('bcp').locator('.bhrigu-prediction-cards').innerText()).includes('personal direction and self-expression'));
    await panel('bcp').getByLabel('Running year', {exact: true}).selectOption('120');
    await ready('bcp');
    assert.equal((await planets('bcp')).length, 5);
    assert.ok((await panel('bcp').innerText()).includes('Cycle ruler defined through year 108'));
    await setMoment('bcp', '2118-09-03T23:59:59');
    await ready('bcp');
    assert.equal(await panel('bcp').locator('.bhrigu-active-period').count(), 5);
    await panel('bcp').getByRole('button', {name: 'Today', exact: true}).click();
    await nav.getByRole('button', {name: 'Bhrigu Sarala Paddhati', exact: true}).click();
    await ready('bsp');
    assert.ok((await panel('bsp').innerText()).includes('No age-timed rule active in running year 29'));
    assert.ok((await prediction('bsp').innerText()).includes('no applicable age-timed BSP rule for running year 29'));
    assert.ok(!(await prediction('bsp').locator('.bhrigu-prediction-cards').innerText()).includes('learning, creativity and children'));
    await panel('bsp').getByLabel('Running year', {exact: true}).selectOption('40');
    await ready('bsp');
    const forty = await panel('bsp').getByRole('table', {name: 'BSP selected year rules', exact: true}).innerText();
    for (const expected of ['Jupiter', 'H7', 'Scorpio', 'H11', 'Pisces', 'Occupied-house activation']) assert.ok(forty.includes(expected));
    assert.equal(await prediction('bsp').getAttribute('data-year'), '40');
    const fortyPrediction = await prediction('bsp').locator('.bhrigu-prediction-cards').innerText();
    assert.ok(fortyPrediction.includes('relationships, agreements and partnerships'));
    assert.ok(fortyPrediction.includes('gains, networks and elder siblings'));
    await panel('bsp').getByLabel('Running year', {exact: true}).selectOption('32');
    assert.equal(await panel('bsp').getByRole('table', {name: 'BSP selected year rules', exact: true}).locator('tbody tr').count(), 3);
    assert.ok((await prediction('bsp').locator('.bhrigu-prediction-cards').innerText()).includes('occasional additional focus'));
    assert.ok((await prediction('bsp').locator('.bhrigu-prediction-cards').innerText()).includes('Controlling influence'));
    await panel('bsp').getByLabel('BSP rule interpretation').selectOption('status');
    await panel('bsp').getByRole('button', {name: 'Today', exact: true}).click();
    await ready('bsp');
    await shot('bhrigu-bsp-desktop.png');
    await nav.getByRole('button', {name: 'Padma Chakra Paddhati', exact: true}).click();
    await ready('padma');
    const direct = await panel('padma').getByRole('table', {name: 'Padma direct Badhaka signs', exact: true}).innerText();
    assert.ok(direct.includes('Virgo') && direct.includes('Mapped to D1 H5'));
    await prediction('padma').getByText('Detailed year predictions & calculations', {exact: true}).click();
    const padmaPrediction = await prediction('padma').getByRole('table', {name: 'Year prediction calculations', exact: true}).innerText();
    assert.ok(padmaPrediction.includes('Annual sign Virgo = Direct Badhaka sign'));
    assert.ok(padmaPrediction.includes('Year-lord D12 sign Gemini = Badhakesh placement'));
    assert.ok(!padmaPrediction.includes('Debilitated'));
    await prediction('padma').getByText('Detailed year predictions & calculations', {exact: true}).click();
    await setMoment('padma', '2026-05-01T12:00');
    await ready('padma');
    assert.equal(await panel('padma').getByLabel('Running year', {exact: true}).inputValue(), '29');
    await shot('bhrigu-padma-desktop.png');
    // Returning to a method retains that method's selection; Today resets it.
    await nav.getByRole('button', {name: 'Bhrigu Chakra Paddhati', exact: true}).click();
    await panel('bcp').getByLabel('Running year', {exact: true}).selectOption('28');
    await setMoment('bcp', '2026-05-01T12:00');
    await ready('bcp');
    assert.equal(await panel('bcp').getByLabel('Running year', {exact: true}).inputValue(), '28');
    // Date changes cannot silently leave the selected annual interval.
    await panel('bcp').getByLabel('Date within year', {exact: true}).fill('01/05/2027');
    assert.ok((await panel('bcp').getByRole('alert').innerText()).includes('inside the selected year'));
    await panel('bcp').getByRole('button', {name: 'Today', exact: true}).click();
    await ready('bcp');
    for (const width of [390, 320]) {
      await page.setViewportSize({width, height: 844});
      await overflow();
      const rect = await panel('bcp').locator('.bhrigu-natal-grid').boundingBox();
      assert.ok(rect.width <= 724 && rect.height <= 440, 'Chart stays within the approved compact size');
      assert.ok(rect.x >= 0 && rect.x + rect.width <= width + 1, 'Chart fits viewport');
      await shot(`bhrigu-bcp-mobile-${width}.png`);
      await prediction('bcp').getByText('Detailed year predictions & calculations', {exact: true}).click();
      await prediction('bcp').getByText('All five dasha readings & calculations', {exact: true}).click();
      await overflow();
      await prediction('bcp').getByText('Detailed year predictions & calculations', {exact: true}).click();
      await prediction('bcp').getByText('All five dasha readings & calculations', {exact: true}).click();
    }
    assert.deepEqual(errors, []);
    assert.deepEqual(external, []);
    console.log('Bhrigu browser checks passed: three methods, selected-year predictions, five-level timing readings, boundaries, recovery, year 120 and mobile.');
  } finally {await browser.close();}
})().catch(e => {console.error(e); process.exitCode = 1;});
